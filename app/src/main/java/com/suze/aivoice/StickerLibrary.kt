    /**
     * 按心情取表情。key 用 [EmotionEngine.Mood] 的名字（HAPPY/SHY/...），
     * 每类 4 个，随机挑一个，让同一心情也不会每次都一样。
     */
    fun moodsFor(mood: String?): String {
        val list = when (mood) {
            "HAPPY" -> listOf("😊", "😄", "🥰", "😆")
            "CALM" -> listOf("🙂", "😌", "🌿", "😇")
            "CURIOUS" -> listOf("🤔", "👀", "🧐", "💡")
            "SHY" -> listOf("😳", "😊", "🙈", "💗")
            "TIRED" -> listOf("😴", "🥱", "😪", "💤")
            "SAD" -> listOf("😢", "🥺", "💧", "😔")
            "ANNOYED" -> listOf("😤", "😠", "😾", "💢")
            else -> listOf("🙂", "😊", "🌸", "😀")
        }
        return list[(Math.random() * list.size).toInt().coerceIn(0, list.size - 1)]
    }

